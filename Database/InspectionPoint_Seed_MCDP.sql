       (SELECT M.MapID FROM dbo.PIP_M_InspectionMap M WHERE M.MapCode=Missing.MapCode AND M.IsActive=1),
       MapX,MapY,DisplayOrder,1,0,@UserID,@UserID
FROM Missing;

