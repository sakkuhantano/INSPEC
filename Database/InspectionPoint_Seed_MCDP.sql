;WITH Missing AS (
 SELECT S.*, ROW_NUMBER() OVER (ORDER BY S.MapCode,S.DisplayOrder) AS RN
 FROM #SeedPoints S
 WHERE NOT EXISTS (SELECT 1 FROM dbo.PIP_M_InspectionPoint P WHERE P.MapID=(SELECT M.MapID FROM dbo.PIP_M_InspectionMap M WHERE M.MapCode=S.MapCode AND M.IsActive=1) AND P.PointCode=S.PointCode)
)
