(InspectionPointID,PointCode,PointName,PointObjectType,PointDescription,ObjectReferenceType,ObjectReferenceID,ObjectReferenceCode,MapID,MapX,MapY,DisplayOrder,IsActive,IsNormalAbnormalRequired,EntryUser,UpdateUser)
